// Packs the dashboard (web/) into hosting/web4-files.ts so the contract can serve it. Run `node rebuild.mjs` first.
import fs from "node:fs";
import path from "node:path";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
};
const files = {};
for (const name of fs.readdirSync("web")) {
  const type = TYPES[path.extname(name)];
  if (type) files[`/${name}`] = { t: type, b: fs.readFileSync(path.join("web", name)).toString("base64") };
}
const out = `// Generated by hosting/gen-web4.mjs from web/. Do not edit by hand.\nexport const WEB4_FILES: Record<string, { t: string; b: string }> = ${JSON.stringify(files)};\n`;
fs.writeFileSync("hosting/web4-files.ts", out);
console.log(`web4: packed ${Object.keys(files).length} files (${Math.round(out.length / 1024)} KB)`);
